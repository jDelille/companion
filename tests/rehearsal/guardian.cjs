const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const fixture=JSON.parse(fs.readFileSync(process.env.DOJANG_FIXTURE_OUTPUT,'utf8'));
const origin='http://localhost:3000',checks=[];
const pass=name=>{checks.push({name,result:'passed'});console.log('PASS '+name);};
const PIN='482913';
let stage='staff sets PIN';
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const staff=await browser.newContext({viewport:{width:1280,height:900}}),page=await staff.newPage();
  page.setDefaultTimeout(20000);
  const hubBodies=[];
  page.on('request',r=>{if(r.url().endsWith('/api/hub')&&r.method()==='POST')hubBodies.push(r.postData()||'');});
  await page.goto(origin+`/hub?memberId=${fixture.guardianChildId}&view=manage&section=kiosk`);
  await page.getByLabel('Login',{exact:true}).fill(fixture.hubLogin);
  await page.getByLabel('Password',{exact:true}).fill(fixture.hubPassword);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  const access=page.getByRole('group',{name:'Kiosk access for Guardian Rehearsal Parent'});
  await access.getByText('No kiosk PIN').waitFor();
  await access.getByLabel('New kiosk PIN for Guardian Rehearsal Parent',{exact:true}).fill(PIN);
  await access.getByLabel('Reason for kiosk PIN for Guardian Rehearsal Parent',{exact:true}).fill('Parent chose a PIN at the desk');
  await access.getByRole('button',{name:'Review kiosk PIN'}).click();
  const review=page.getByRole('group',{name:'Review member action'});
  await review.getByText(/stored as a secure hash/).waitFor();
  assert.equal((await review.innerText()).includes(PIN),false);
  await review.getByRole('button',{name:'Confirm member action in Odoo'}).click();
  await page.getByLabel('Member action result').getByText(/Kiosk PIN saved in Odoo as a secure hash\. It was not sent anywhere/).waitFor();
  await access.getByText(/PIN set .* by Demo Hub Manager/).waitFor();
  assert.equal(hubBodies.filter(b=>b.includes('set_guardian_kiosk_pin')).length,1);
  pass('a manager sets a household parent’s kiosk PIN after review; the PIN is never displayed back');
  await staff.close();
  stage='kiosk pairing';
  const kioskContext=await browser.newContext({viewport:{width:1280,height:900}}),kiosk=await kioskContext.newPage();
  kiosk.setDefaultTimeout(20000);
  await kiosk.goto(origin+'/integration/pair');
  await kiosk.getByLabel('Access',{exact:true}).click();await kiosk.locator('[role=option][data-value="kiosk"]').click();
  await kiosk.locator('input[name=pairKey]').fill(process.env.DOJANG_KIOSK_PAIR_KEY);
  await kiosk.getByRole('button',{name:'Connect test device'}).click();
  await kiosk.waitForURL('**/kiosk');
  let checkins=[],dropNext=false;
  await kiosk.route('**/api/v2/guardian/check-ins',async route=>{
   checkins.push(route.request().postDataJSON());const response=await route.fetch();
   if(dropNext){dropNext=false;return route.abort('failed');}
   return route.fulfill({response});
  });
  await kiosk.getByRole('button',{name:/^Check In/i}).click();
  await kiosk.getByRole('button',{name:/Guardian class/}).click();
  await kiosk.getByRole('button',{name:'Parent check-in with phone and PIN'}).click();
  const panel=kiosk.getByRole('region',{name:'Parent check-in'});
  stage='wrong PIN';
  await panel.getByLabel('Parent phone number',{exact:true}).fill('(512) 555-0177');
  await panel.getByLabel('Parent kiosk PIN',{exact:true}).fill('000111');
  await panel.getByRole('button',{name:'Verify parent'}).click();
  await panel.getByRole('alert').getByText(/could not verify that phone number and PIN/).waitFor();
  assert.equal(await panel.getByText('Mia R.').count(),0);
  stage='verified family check-in with lost response';
  await panel.getByLabel('Parent phone number',{exact:true}).fill('(512) 555-0177');
  await panel.getByLabel('Parent kiosk PIN',{exact:true}).fill(PIN);
  await panel.getByRole('button',{name:'Verify parent'}).click();
  const child=panel.getByRole('group',{name:'Student Mia R.'});
  await child.waitFor();
  assert.equal(await panel.getByText(/Demo S\.|Recovery S\.|Followup S\./).count(),0);
  dropNext=true;
  await child.getByRole('button',{name:'Check in Mia R.'}).click();
  await child.getByText(/could not confirm Mia R\.'s check-in/).waitFor();
  await child.getByRole('button',{name:'Try Mia R. again'}).click();
  await child.getByText(/Mia R\. is checked in/).waitFor();
  assert.equal(checkins.length,2);
  assert.deepEqual(checkins[0].command,checkins[1].command);
  assert.equal(checkins[0].guardianToken,checkins[1].guardianToken);
  await kiosk.screenshot({path:path.join(process.env.DOJANG_EVIDENCE_DIR,'guardian-kiosk.png'),fullPage:true});
  pass('a verified parent sees only their own child and a lost check-in response replays the same native attendance');
  await panel.getByRole('button',{name:'Done'}).click();
  assert.equal(await kiosk.getByText('Mia R.').count(),0);
  pass('closing the parent panel removes the family list from the shared kiosk');
  fs.writeFileSync(path.join(process.env.DOJANG_EVIDENCE_DIR,'guardian-browser-results.json'),JSON.stringify({mode:'real Odoo synthetic records',checks},null,2));
  await kioskContext.close();
 }finally{await browser.close();}
})().catch(e=>{console.error(`Guardian rehearsal failed at ${stage}: ${e.message}`);process.exitCode=1;});
