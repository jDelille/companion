const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const fixture=JSON.parse(fs.readFileSync(process.env.DOJANG_FIXTURE_OUTPUT,'utf8'));
const origin='http://localhost:3000',checks=[];
const pass=name=>{checks.push({name,result:'passed'});console.log('PASS '+name);};
const BODY='Belt testing day reminder: arrive 15 minutes early.';
let stage='login';
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const context=await browser.newContext({viewport:{width:1280,height:900}}),page=await context.newPage();
  page.setDefaultTimeout(20000);
  let commands=[],dropNext=false;
  await page.route('**/api/hub',async route=>{
   const data=route.request().postDataJSON();
   if(!['record_consent','create_broadcast','approve_broadcast','cancel_broadcast','set_automation_active'].includes(data.operation))return route.continue();
   commands.push(data);const response=await route.fetch();
   if(dropNext){dropNext=false;return route.abort('failed');}
   return route.fulfill({response});
  });
  await page.goto(origin+'/hub?view=communications');
  await page.getByLabel('Login',{exact:true}).fill(fixture.hubLogin);
  await page.getByLabel('Password',{exact:true}).fill(fixture.hubPassword);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  const review=page.getByLabel('Review communications action',{exact:true});
  const result=()=>page.getByLabel('Communications result',{exact:true});
  const confirm=async()=>{await review.getByRole('checkbox').check();await review.getByRole('button',{name:'Confirm communications action in Odoo'}).click();};
  stage='consent';
  const consent=page.getByRole('region',{name:'Consent',exact:true});
  await consent.getByLabel('Student for consent',{exact:true}).selectOption(fixture.guardianChildId);
  const parent=consent.getByRole('group',{name:'Consent for Guardian Rehearsal Parent'});
  await parent.getByText(/SMS •••0177 · service not recorded · marketing not recorded/).waitFor();
  await parent.getByLabel('Consent evidence for Guardian Rehearsal Parent',{exact:true}).fill('Signed the enrolment form');
  await parent.getByRole('button',{name:'Review consent change'}).click();
  await review.getByText(/SMS marketing consent granted \(paper form\)/).waitFor();
  await confirm();
  await result().getByText(/Consent saved in Odoo with its source and evidence\. No message was sent\./).waitFor();
  await parent.getByText(/SMS •••0177 · service not recorded · marketing granted/).waitFor();
  pass('marketing consent is recorded with source, evidence and history');
  stage='broadcast with lost response';
  const broadcast=page.getByRole('region',{name:'Broadcast',exact:true});
  await broadcast.getByLabel('Broadcast name',{exact:true}).fill('Rehearsal testing day');
  await broadcast.getByLabel('Purpose',{exact:true}).selectOption('marketing');
  await broadcast.getByLabel('Audience',{exact:true}).selectOption({label:'Class: Guardian class'});
  await broadcast.getByLabel('Message',{exact:true}).fill(BODY);
  await broadcast.getByRole('button',{name:'Preview audience'}).click();
  const preview=broadcast.getByRole('region',{name:'Broadcast preview'});
  await preview.getByText('1 recipients in Class: Guardian class.').waitFor();
  await preview.getByText(/Guardian Rehearsal Parent · •••0177/).waitFor();
  await preview.getByLabel('Reason for this broadcast',{exact:true}).fill('Testing day logistics');
  await preview.getByRole('button',{name:'Review broadcast'}).click();
  await review.getByText(/Nothing is queued or sent yet\./).waitFor();
  dropNext=true;await confirm();
  await page.getByRole('button',{name:'Check communications result'}).click();
  await result().getByText(/Broadcast saved for approval with 1 recipients\. Nothing is queued or sent yet\./).waitFor();
  const creates=commands.filter(c=>c.operation==='create_broadcast');
  assert.equal(creates.length,2);assert.equal(creates[0].requestKey,creates[1].requestKey);
  pass('a consented audience is previewed, frozen and saved once despite a lost response');
  stage='approval';
  const row=broadcast.getByRole('group',{name:'Broadcast Rehearsal testing day'});
  await row.getByLabel('Reason for Rehearsal testing day',{exact:true}).fill('Wording checked');
  await row.getByRole('button',{name:'Review approval'}).click();
  await review.getByText(/count as sent only when the provider confirms/).waitFor();
  await confirm();
  await result().getByText(/Broadcast approved: 1 messages queued\. No provider is connected, so nothing is sent\./).waitFor();
  await row.getByText(/approved by Demo Hub Manager/).waitFor();
  await page.screenshot({path:path.join(process.env.DOJANG_EVIDENCE_DIR,'comms-approved.png'),fullPage:true});
  pass('approval rechecks consent and queues without claiming delivery');
  stage='automations';
  const automations=page.getByRole('region',{name:'Automations',exact:true});
  await automations.getByText(/Rule · dojo_crm/).first().waitFor();
  assert.equal(await automations.getByRole('button',{name:/Review pause|Review resume/}).count(),0);
  pass('native automations are listed and a manager cannot pause them');
  fs.writeFileSync(path.join(process.env.DOJANG_EVIDENCE_DIR,'comms-browser-results.json'),JSON.stringify({mode:'real Odoo synthetic records',checks},null,2));
  await context.close();
 }finally{await browser.close();}
})().catch(e=>{console.error(`Communications rehearsal failed at ${stage}: ${e.message}`);process.exitCode=1;});
