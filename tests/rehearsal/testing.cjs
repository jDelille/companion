const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const fixture=JSON.parse(fs.readFileSync(process.env.DOJANG_FIXTURE_OUTPUT,'utf8'));
const origin='http://localhost:3000',checks=[];
const pass=name=>{checks.push({name,result:'passed'});console.log('PASS '+name);};
const [studentA,studentB]=fixture.testingMemberIds;
let stage='login';
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const context=await browser.newContext({viewport:{width:1280,height:900}}),page=await context.newPage();
  page.setDefaultTimeout(20000);
  const call=async(op,payload)=>{const r=await context.request.post(origin+'/api/hub',{headers:{origin},data:{operation:op,payload,requestKey:null}});return r.json();};
  let commands=[],dropNext=false;
  await page.route('**/api/hub',async route=>{
   const data=route.request().postDataJSON();
   if(!['save_testing_roster','record_test_results','promote_test_results','reverse_promotion'].includes(data.operation))return route.continue();
   commands.push(data);const response=await route.fetch();
   if(dropNext){dropNext=false;assert.equal(response.status(),200);return route.abort('failed');}
   return route.fulfill({response});
  });
  await page.goto(origin+'/hub?view=testing');
  await page.getByLabel('Login',{exact:true}).fill(fixture.hubLogin);
  await page.getByLabel('Password',{exact:true}).fill(fixture.hubPassword);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  const section=page.getByRole('region',{name:'Testing eligibility',exact:true});
  const review=page.getByLabel('Review testing action',{exact:true});
  const result=()=>page.getByLabel('Testing result',{exact:true});
  const confirm=async()=>{await review.getByRole('checkbox').check();await review.getByRole('button',{name:'Confirm testing action in Odoo'}).click();};
  stage='eligibility and roster with lost response';
  await section.getByLabel('Find students',{exact:true}).fill('Testing Student');
  await section.getByRole('button',{name:'Search students'}).click();
  await section.getByRole('group',{name:'Eligibility for Testing Student B'}).getByText(/White Belt → Yellow Belt · Eligible · 2\/2 classes/).waitFor();
  await section.getByLabel('Add Testing Student A',{exact:true}).check();
  await section.getByLabel('Add Testing Student B',{exact:true}).check();
  await section.getByLabel('Test name',{exact:true}).fill('Rehearsal belt testing');
  await section.getByLabel('Reason for this roster',{exact:true}).fill('Both reached the attendance threshold');
  await section.getByRole('button',{name:'Review testing roster'}).click();
  await review.getByText(/No belt, invoice or message is created\./).waitFor();
  dropNext=true;await confirm();
  await page.getByRole('button',{name:'Check testing result'}).click();
  await result().getByText(/Testing roster saved in Odoo with 2 students\. No rank, invoice or message was created\./).waitFor();
  assert.equal(commands.length,2);assert.equal(commands[0].requestKey,commands[1].requestKey);assert.deepEqual(commands[0].payload,commands[1].payload);
  const roster=page.getByRole('region',{name:'Testing roster',exact:true});
  await roster.getByRole('heading',{name:'Rehearsal belt testing'}).waitFor();
  pass('a testing roster is built from eligibility and a lost response replays one native test');
  stage='results';
  await roster.getByLabel('Result for Testing Student A',{exact:true}).selectOption('pass');
  await roster.getByLabel('Result for Testing Student B',{exact:true}).selectOption('fail');
  await roster.getByLabel('Reason for results',{exact:true}).fill('Panel decision');
  await roster.getByRole('button',{name:'Review results'}).click();
  await review.getByText('Testing Student A: pending → pass').waitFor();
  await confirm();
  await result().getByText(/Test results saved in Odoo \(2 changed\)\. No belt was awarded yet\./).waitFor();
  assert.equal((await call('member_details',{memberId:studentA})).member.rank,'White Belt');
  pass('results are saved without awarding a belt');
  stage='bulk promotion';
  await roster.getByLabel('Promote Testing Student A',{exact:true}).check();
  await roster.getByRole('button',{name:'Preview promotions'}).click();
  const preview=roster.getByRole('region',{name:'Promotion preview',exact:true});
  await preview.getByText('Testing Student A: White Belt → Yellow Belt').waitFor();
  await preview.getByLabel('Reason for promotions',{exact:true}).fill('Passed the panel');
  await preview.getByRole('button',{name:'Review promotions'}).click();
  await confirm();
  await result().getByText(/Promotions saved in Odoo: 1 belt awards\. No message or invoice\./).waitFor();
  assert.equal((await call('member_details',{memberId:studentA})).member.rank,'Yellow Belt');
  assert.equal((await call('member_details',{memberId:studentB})).member.rank,'White Belt');
  await page.screenshot({path:path.join(process.env.DOJANG_EVIDENCE_DIR,'testing-promoted.png'),fullPage:true});
  pass('only the reviewed passing student is promoted and the belt reads back on the member');
  stage='reversal';
  const history=page.getByRole('region',{name:'Promotion history',exact:true});
  await history.getByLabel('Find promotion history',{exact:true}).fill('Testing Student A');
  await history.getByRole('button',{name:'Search history'}).click();
  const award=history.getByRole('group',{name:'Award Yellow Belt for Testing Student A'});
  await award.getByLabel('Reason for reversing Testing Student A',{exact:true}).fill('Recorded on the wrong student');
  await award.getByRole('button',{name:'Review reversal'}).click();
  await confirm();
  await result().getByText(/Promotion reversed in Odoo: Yellow Belt → White Belt\./).waitFor();
  assert.equal((await call('member_details',{memberId:studentA})).member.rank,'White Belt');
  await award.getByText(/reversed by .*: Recorded on the wrong student/).waitFor();
  pass('a promotion reversal is reviewed, kept in history and restores the previous belt');
  fs.writeFileSync(path.join(process.env.DOJANG_EVIDENCE_DIR,'testing-browser-results.json'),JSON.stringify({mode:'real Odoo synthetic records',checks},null,2));
  await context.close();
 }finally{await browser.close();}
})().catch(e=>{console.error(`Testing rehearsal failed at ${stage}: ${e.message}`);process.exitCode=1;});
